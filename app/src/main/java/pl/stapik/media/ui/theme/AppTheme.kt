package pl.stapik.media.ui.theme

/** Matches the three desktop themes 1:1 (Settings -> Theme on desktop). */
enum class AppTheme {
    CLASSIC,
    MODERN,
    CLASSIC_PINK,
}

/** Whether a theme uses the skeuomorphic Win98 bevel look or a flat/rounded one. */
enum class ThemeShape {
    BEVEL,
    FLAT,
}
